export function ProjectIcon({
  name,
  size = 22,
  className,
}: {
  name: string;
  size?: number;
  className?: string;
}) {
  const Icon = Object.prototype.hasOwnProperty.call(projectIcons, name)
    ? projectIcons[name]
    : FolderCode;

  return (
    <Icon
      size={size}
      className={`shrink-0${className ? ` ${className}` : ''}`}
      aria-hidden="true"
      focusable="false"
    />
  );
}

